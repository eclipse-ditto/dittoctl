"""Every source file carries the EPL-2.0 header; files largely generated by an AI also carry the AI disclosure.

Markdown files carry no header: NOTICE.md declares the licences and the use of generative AI for them.
"""

from __future__ import annotations

import re
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent


def source_files() -> list[Path]:
    files = [ROOT / "pyproject.toml", *(ROOT / ".github" / "workflows").glob("*.yml")]
    for directory in ("src", "tests", "scripts"):
        files += (ROOT / directory).rglob("*.py")
    return sorted(f for f in files if "__pycache__" not in f.parts)


def header_of(path: Path) -> str:
    lines = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.startswith("#"):
            break
        lines.append(line.removeprefix("#").strip())
    return "\n".join(lines)


@pytest.mark.parametrize("path", source_files(), ids=lambda p: str(p.relative_to(ROOT)))
def test_license_header(path: Path):
    header = header_of(path)
    assert re.match(r"Copyright \(c\) \d{4} Contributors to the Eclipse Foundation\n", header), "no copyright line"
    assert "terms of the Eclipse Public License 2.0" in header
    spdx = re.search(r"^SPDX-License-Identifier: (.+)$", header, re.M)
    assert spdx, "no SPDX-License-Identifier"
    disclosed = "AI Disclosure:" in header
    if disclosed:
        assert spdx.group(1) == "EPL-2.0 AND CC0-1.0", "AI-generated portions are CC0-1.0"
        assert re.search(r"^Assisted-by: \S.+$", header, re.M), "the AI assistant isn't named"
    else:
        assert spdx.group(1) == "EPL-2.0", "CC0-1.0 only applies to AI-generated portions"
